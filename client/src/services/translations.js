export function getTranslation(key, language = 'en-IN', params = {}) {
  const langKey = language.startsWith('ta') ? 'ta-IN' : language.startsWith('te') ? 'te-IN' : 'en-IN';
  let text = TRANSLATIONS[langKey]?.[key] || TRANSLATIONS['en-IN']?.[key] || key;
  
  // Replace params like {current}, {total}
  Object.keys(params).forEach(p => {
    text = text.replace(new RegExp(`\\{${p}\\}`, 'g'), params[p]);
  });
  
  return text;
}

